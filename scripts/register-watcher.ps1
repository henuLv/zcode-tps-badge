# Arm the swap watcher via Task Scheduler (svchost-detached, highest run level).
# ASCII-only comments: PS5.1 reads BOM-less .ps1 as ANSI/GBK, UTF-8 Chinese comments corrupt parsing.
# Usage: powershell -File register-watcher.ps1 [-LogSuffix <version>] [-Remove]
param(
  [string]$LogSuffix = "",
  [switch]$Remove
)
$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot   # scripts/ -> repo root
$taskName = "tps-watcher"

if ($Remove) {
  Unregister-ScheduledTask -TaskName $taskName -Confirm:$false -ErrorAction SilentlyContinue
  # also kill any waiting watcher processes (self cmdline contains neither pattern)
  Get-CimInstance Win32_Process -Filter "Name = 'powershell.exe'" | Where-Object {
    $_.ProcessId -ne $PID -and ($_.CommandLine -like '*watcher-wrapper*' -or $_.CommandLine -like '*apply-patch.ps1*')
  } | ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }
  Write-Output "TASK_REMOVED"
  exit 0
}

# kill any previous watcher instances (exclude self by script path in command line)
Get-CimInstance Win32_Process -Filter "Name = 'powershell.exe'" | Where-Object {
  $_.ProcessId -ne $PID -and $_.CommandLine -like '*apply-patch.ps1*'
} | ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }

# fresh official asar backup (restore.ps1 source; must track current version)
$asar = "C:\Program Files\ZCode\resources\app.asar"
Copy-Item $asar ($asar + ".bak-tps") -Force
Write-Output "BACKUP_UPDATED"

$logName = if ($LogSuffix) { "apply-$LogSuffix.log" } else { "apply-current.log" }
$wrapper = Join-Path $repo ".tmp\watcher-wrapper.ps1"
New-Item -ItemType Directory -Force (Split-Path $wrapper) | Out-Null
Remove-Item (Join-Path $repo ".tmp\$logName") -ErrorAction SilentlyContinue
# wrapper v5: heartbeat + probe + try/catch, single-line apply-patch call (no backtick continuation)
@"
# auto-generated by register-watcher.ps1 - ASCII only
`$repo = "$repo"
`$log = "`$repo\.tmp\$logName"
function Log(`$m) { Add-Content -Path `$log -Value ("[{0}] {1}" -f (Get-Date -Format 'HH:mm:ss.fff'), `$m) }
Log "wrapper started pid=`$PID"
try {
  Set-Content -Path "C:\Program Files\ZCode\resources\.tps-probe" -Value "probe" -ErrorAction Stop
  Log "probe: Program Files write OK"
  Remove-Item "C:\Program Files\ZCode\resources\.tps-probe" -ErrorAction SilentlyContinue
} catch {
  Log "probe: WRITE DENIED: `$(`$_.Exception.Message)"
}
try {
  Log "invoke apply-patch.ps1"
  & `$repo\scripts\apply-patch.ps1 -PatchedPath `$repo\logs\build\app.asar.patched 2>&1 | ForEach-Object { Log "`$_" }
  Log "apply-patch finished"
} catch {
  Log "FATAL: `$(`$_.Exception.Message)"
}
Log "wrapper exit"
"@ | Set-Content -Path $wrapper -Encoding ASCII

$action = New-ScheduledTaskAction -Execute "powershell.exe" -Argument "-NoProfile -ExecutionPolicy Bypass -File `"$wrapper`""
$trigger = New-ScheduledTaskTrigger -Once -At (Get-Date).AddSeconds(5)
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit (New-TimeSpan -Minutes 30)
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Settings $settings -RunLevel Highest -Force | Out-Null
Write-Output "TASK_REGISTERED_RUNLEVEL_HIGHEST"
